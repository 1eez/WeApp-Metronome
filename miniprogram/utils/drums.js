function decodeSample(buffer) {
  const view = new DataView(buffer)
  // Bundled assets are generated by scripts/prepare-drums.py with a standard header.
  if (view.getUint16(20, true) !== 1 || view.getUint16(22, true) !== 1 || view.getUint32(24, true) !== SAMPLE_RATE || view.getUint16(34, true) !== 16) throw new Error('鼓采样格式不正确')
  const length = view.getUint32(40, true) / 2
  const result = new Float32Array(length)
  for (let i = 0; i < length; i++) result[i] = view.getInt16(44 + i * 2, true) / 32768
  return result
}

function createDrumRenderer(bpm, patternId, samples, beats = 4) {
  const preset = patterns.find(item => item.id === patternId)
  const pattern = { hits: {} }
  for (const instrument of Object.keys(preset.hits)) pattern.hits[instrument] = preset.hits[instrument].filter(hit => hit < beats)
  const samplesPerBeat = SAMPLE_RATE * 60 / bpm
  const barLength = samplesPerBeat * beats
  const instruments = Object.keys(pattern.hits)
  const gains = { kick: 0.65, snare: 0.5, hat: 0.22 }
  // Bound simultaneous sample tails across bars; use one gain for the whole track.
  let bound = 0
  for (const instrument of instruments) {
    const duration = samples[instrument].length
    const offsets = pattern.hits[instrument]
    const lookback = Math.ceil(duration / barLength) + 1
    let overlaps = 1
    for (const offset of offsets) {
      const end = Math.round(offset * samplesPerBeat)
      let count = 0
      for (let bar = -lookback; bar <= 0; bar++) {
        for (const hit of offsets) {
          const start = Math.round((bar * beats + hit) * samplesPerBeat)
          if (start <= end && end - start < duration + 1) count++
        }
      }
      overlaps = Math.max(overlaps, count)
    }
    bound += gains[instrument] * overlaps
  }
  const scale = 0.9 / Math.max(1, bound)
  return second => {
    const start = second * SAMPLE_RATE
    const end = start + SAMPLE_RATE
    const mix = new Float32Array(SAMPLE_RATE)
    for (const instrument of instruments) {
      const sample = samples[instrument]
      const firstBar = Math.max(0, Math.floor((start - sample.length - 1) / barLength))
      const lastBar = Math.floor(end / barLength)
      for (let bar = firstBar; bar <= lastBar; bar++) {
        for (const offset of pattern.hits[instrument]) {
          const hit = Math.round((bar * beats + offset) * samplesPerBeat)
          const from = Math.max(start, hit)
          const to = Math.min(end, hit + sample.length)
          for (let position = from; position < to; position++) mix[position - start] += sample[position - hit] * gains[instrument]
        }
      }
    }
    const buffer = new ArrayBuffer(SAMPLE_RATE * 2)
    const view = new DataView(buffer)
    for (let i = 0; i < mix.length; i++) view.setInt16(i * 2, Math.round(mix[i] * scale * 32767), true)
    return buffer
  }
}

module.exports = { kits, patterns, decodeSample, createDrumRenderer }
